-- Общий вес накладной = сумма (количество * средний вес груза).
-- Триггер trg_waybill_year_weight при этом пересчитает
-- нарастающий итог client.year_weight для накладных текущего года.
UPDATE waybill w
   SET total_weight = s.total
  FROM (SELECT wi.waybill_id, SUM(wi.quantity * c.avg_weight) AS total
          FROM waybill_item wi
          JOIN cargo c ON c.cargo_id = wi.cargo_id
         GROUP BY wi.waybill_id) s
 WHERE w.waybill_id = s.waybill_id;

